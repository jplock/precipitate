//! Name handling: slugs, environment tokens, prefixes, layers.

use precip_types::{EnvName, WorkloadName};
use std::collections::BTreeMap;
use std::fmt;

/// A name lowercased with every run of other characters collapsed to one
/// hyphen, so names from tags, stacks and resources compare equal.
#[derive(Debug, Clone, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Slug(String);

impl Slug {
    pub fn new(s: &str) -> Self {
        let mut out = String::with_capacity(s.len());
        let mut last_dash = true;
        for c in s.chars() {
            if c.is_ascii_alphanumeric() {
                out.push(c.to_ascii_lowercase());
                last_dash = false;
            } else if !last_dash {
                out.push('-');
                last_dash = true;
            }
        }
        while out.ends_with('-') {
            out.pop();
        }
        Self(out)
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    fn segments(&self) -> impl Iterator<Item = &str> {
        self.0.split('-')
    }

    fn joined<'a>(parts: impl IntoIterator<Item = &'a str>) -> Self {
        Self(parts.into_iter().collect::<Vec<_>>().join("-"))
    }

    /// Whether `root` is this name or its leading segments.
    fn starts_with_segments(&self, root: &Self) -> bool {
        !root.is_empty()
            && (self.0 == root.0
                || self
                    .0
                    .strip_prefix(root.as_str())
                    .is_some_and(|rest| rest.starts_with('-')))
    }

    /// Split an environment token out, returning the remaining name and
    /// the canonical environment. The end is checked first, then the
    /// start, then any middle segment, so `app-dev-api` is `app-api` in
    /// `dev`.
    pub fn split_environment(
        &self,
        tokens: &BTreeMap<String, EnvName>,
    ) -> Option<(Self, EnvName)> {
        let parts: Vec<&str> = self.segments().collect();
        if parts.len() < 2 {
            return None;
        }
        let order = std::iter::once(parts.len() - 1)
            .chain(std::iter::once(0))
            .chain(1..parts.len() - 1);
        for i in order {
            if let Some(env) = tokens.get(parts[i]) {
                let rest = parts
                    .iter()
                    .enumerate()
                    .filter(|(j, _)| *j != i)
                    .map(|(_, p)| *p);
                return Some((Self::joined(rest), env.clone()));
            }
        }
        None
    }

    /// Drop a trailing segment that looks generated by CloudFormation or
    /// SAM: 10 to 14 alphanumerics containing at least one digit, such as
    /// the `7EMKNZP5FCB9` on `inbox-prod-rMailTable-7EMKNZP5FCB9`.
    pub fn without_generated_suffix(self) -> Self {
        let Some((head, tail)) = self.0.rsplit_once('-') else { return self };
        let looks_generated = (10..=14).contains(&tail.len())
            && tail.chars().all(|c| c.is_ascii_alphanumeric())
            && tail.chars().any(|c| c.is_ascii_digit());
        if looks_generated { Self(head.to_string()) } else { self }
    }

    /// Remove one trailing layer token (`-vpc`, `-app`, `-db`) when a name
    /// remains, so the layers of one workload share a name.
    pub fn without_layer(self, layers: &[String]) -> Self {
        match self.0.rsplit_once('-') {
            Some((head, tail))
                if !head.is_empty() && layers.iter().any(|l| l == tail) =>
            {
                Self(head.to_string())
            }
            _ => self,
        }
    }

    /// The longest known name this one equals or starts with.
    pub fn longest_prefix<'a>(&self, known: &'a [Self]) -> Option<&'a Self> {
        known
            .iter()
            .filter(|k| self.starts_with_segments(k))
            .max_by_key(|k| k.0.len())
    }

    /// The shortest known name this one equals or starts with, for finding
    /// the most general shared root among sibling names. Equality counts
    /// so two resources with the same root join.
    pub fn shortest_prefix<'a>(&self, known: &'a [Self]) -> Option<&'a Self> {
        known
            .iter()
            .filter(|k| self.starts_with_segments(k))
            .min_by_key(|k| k.0.len())
    }

    /// A known name that appears whole inside this one as a run of
    /// segments, for example `vouch` in `cert-renewal-us-vouch-sh`.
    /// Longest known name wins.
    pub fn contains_segments<'a>(&self, known: &'a [Self]) -> Option<&'a Self> {
        let padded = format!("-{}-", self.0);
        known
            .iter()
            .filter(|k| !k.is_empty() && padded.contains(&format!("-{}-", k.0)))
            .max_by_key(|k| k.0.len())
    }

    /// The root shared with siblings: the leading segments common to the
    /// most siblings, longest on a tie. A one-segment root needs at least
    /// three members in all; a longer root needs two. Roots that are bare
    /// environment tokens are ignored.
    pub fn shared_root(
        &self,
        siblings: &[Self],
        tokens: &BTreeMap<String, EnvName>,
    ) -> Option<Self> {
        let segments: Vec<&str> = self.segments().collect();
        // (siblings sharing it, root)
        let mut best: Option<(usize, Self)> = None;
        for k in 1..segments.len() {
            let root = Self::joined(segments[..k].iter().copied());
            if tokens.contains_key(root.as_str()) {
                continue;
            }
            let count = siblings
                .iter()
                .filter(|s| s.starts_with_segments(&root))
                .count();
            let members = count + 1;
            let enough = if k == 1 { members >= 3 } else { members >= 2 };
            if !enough {
                continue;
            }
            let better = best.as_ref().is_none_or(|(c, r)| {
                count > *c || (count == *c && root.0.len() > r.0.len())
            });
            if better {
                best = Some((count, root));
            }
        }
        best.map(|(_, root)| root)
    }
}

impl fmt::Display for Slug {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.pad(&self.0)
    }
}

impl From<Slug> for WorkloadName {
    fn from(s: Slug) -> Self {
        Self::from(s.0)
    }
}

impl From<Slug> for EnvName {
    fn from(s: Slug) -> Self {
        Self::from(s.0)
    }
}

impl PartialEq<WorkloadName> for Slug {
    fn eq(&self, other: &WorkloadName) -> bool {
        self.0 == other.as_str()
    }
}

/// An account's name and the name of its organizational unit, either of
/// which can say which environment the account holds.
#[derive(Debug, Clone, Copy, Default)]
pub(super) struct AccountNames<'a> {
    pub name: Option<&'a str>,
    pub ou: Option<&'a str>,
}

impl AccountNames<'_> {
    /// The environment the OU name contains, or the account name starts or
    /// ends with. Longest token wins.
    pub(super) fn environment(
        &self,
        tokens: &BTreeMap<String, EnvName>,
    ) -> Option<EnvName> {
        let account = self.name.map(Slug::new);
        let ou = self.ou.map(Slug::new);
        let mut best: Option<(&str, &EnvName)> = None;
        for (token, env) in tokens {
            let hit = ou.as_ref().is_some_and(|o| o.0.contains(token.as_str()))
                || account.as_ref().is_some_and(|a| {
                    a.0.ends_with(&format!("-{token}"))
                        || a.0.starts_with(&format!("{token}-"))
                });
            if hit && best.is_none_or(|(t, _)| token.len() > t.len()) {
                best = Some((token, env));
            }
        }
        best.map(|(_, env)| env.clone())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tokens() -> BTreeMap<String, EnvName> {
        precip_types::GroupingConfig::default().environment_tokens
    }

    fn s(name: &str) -> Slug {
        Slug::new(name)
    }

    fn slugs(names: &[&str]) -> Vec<Slug> {
        names.iter().map(|n| s(n)).collect()
    }

    fn split(name: &str) -> Option<(String, String)> {
        s(name)
            .split_environment(&tokens())
            .map(|(rest, env)| (rest.to_string(), env.to_string()))
    }

    fn pair(rest: &str, env: &str) -> Option<(String, String)> {
        Some((rest.to_string(), env.to_string()))
    }

    #[test]
    fn slug_normalises_names() {
        assert_eq!(s("Search API (v2)").as_str(), "search-api-v2");
        assert_eq!(s("--a--").as_str(), "a");
        assert_eq!(s("billing_prod.v1").as_str(), "billing-prod-v1");
        assert!(s("--").is_empty());
    }

    #[test]
    fn environment_splits_from_either_end_and_canonicalises() {
        assert_eq!(split("billing-prod"), pair("billing", "prod"));
        assert_eq!(split("production-billing"), pair("billing", "prod"));
        assert_eq!(split("billing"), None);
        assert_eq!(
            split("prod"),
            None,
            "a bare token is a name, not an environment"
        );
    }

    #[test]
    fn environment_token_in_the_middle_is_found_last() {
        assert_eq!(split("app-dev-api"), pair("app-api", "dev"));
        assert_eq!(
            split("app-prod-discord-reminders"),
            pair("app-discord-reminders", "prod")
        );
    }

    #[test]
    fn generated_suffixes_are_stripped() {
        let strip = |n: &str| s(n).without_generated_suffix().to_string();
        assert_eq!(
            strip("inbox-prod-rmailtable-7emknzp5fcb9"),
            "inbox-prod-rmailtable"
        );
        assert_eq!(strip("inbox-prod-rmailtable"), "inbox-prod-rmailtable");
        assert_eq!(strip("ami-cleanup"), "ami-cleanup");
        assert_eq!(
            strip("x-abcdefghijkl"),
            "x-abcdefghijkl",
            "no digit, not generated"
        );
        assert_eq!(strip("abcdefghij12"), "abcdefghij12", "one segment stays");
    }

    #[test]
    fn account_and_ou_names_carry_an_environment() {
        let t = tokens();
        let env = |name: Option<&str>, ou: Option<&str>| {
            AccountNames { name, ou }.environment(&t).map(|e| e.to_string())
        };
        assert_eq!(env(Some("payments-prod"), None), Some("prod".into()));
        assert_eq!(
            env(Some("payments"), Some("NonProd")),
            Some("nonprod".into())
        );
        assert_eq!(env(Some("payments"), Some("Infrastructure")), None);
        assert_eq!(env(Some("production-tools"), None), Some("prod".into()));
        assert_eq!(env(None, None), None);
    }

    #[test]
    fn longest_prefix_prefers_the_most_specific_name() {
        let known = slugs(&["vouch", "vouch-us", "inbox", ""]);
        let longest =
            |n: &str| s(n).longest_prefix(&known).map(ToString::to_string);
        assert_eq!(
            longest("vouch-us-prod-instance-refresh"),
            Some("vouch-us".into())
        );
        assert_eq!(longest("vouch"), Some("vouch".into()));
        assert_eq!(longest("voucher-x"), None, "prefix must end at a hyphen");
    }

    #[test]
    fn shortest_prefix_finds_the_shared_root() {
        let known = slugs(&["fairfieldct-ai", "fairfieldct-ai-api"]);
        let shortest =
            |n: &str| s(n).shortest_prefix(&known).map(ToString::to_string);
        assert_eq!(
            shortest("fairfieldct-ai-api-v2"),
            Some("fairfieldct-ai".into())
        );
        assert_eq!(
            shortest("fairfieldct-ai"),
            Some("fairfieldct-ai".into()),
            "an identical sibling root counts"
        );
    }

    #[test]
    fn contains_segments_matches_whole_segments_only() {
        let known = slugs(&["vouch", "us"]);
        assert_eq!(
            s("cert-renewal-us-vouch-sh").contains_segments(&known),
            Some(&s("vouch"))
        );
        assert_eq!(s("voucher-renewal").contains_segments(&known), None);
    }

    #[test]
    fn shared_root_picks_the_root_most_siblings_share() {
        let t = tokens();
        let sibs = slugs(&[
            "serverless-create-root-ca",
            "serverless-issuing-ca-crl",
            "serverless-root-ca-crl",
            "serverless-tls-cert",
            "serverless-expiry",
        ]);
        assert_eq!(
            s("serverless-create-issuing-ca").shared_root(&sibs, &t),
            Some(s("serverless"))
        );
        assert_eq!(
            s("aws-messaging-webhook")
                .shared_root(&slugs(&["aws-quicksetup-ssm"]), &t),
            None,
            "one segment needs three members"
        );
        assert_eq!(
            s("inbox-mail-webhook")
                .shared_root(&slugs(&["inbox-mail-sender"]), &t),
            Some(s("inbox-mail"))
        );
        assert_eq!(
            s("prod-a-b").shared_root(&slugs(&["prod-a-c", "prod-x"]), &t),
            Some(s("prod-a")),
            "a bare environment token is never a root"
        );
    }

    #[test]
    fn layer_tokens_fold_into_the_workload_name() {
        let layers = precip_types::GroupingConfig::default().layer_tokens;
        let strip = |n: &str| s(n).without_layer(&layers).to_string();
        assert_eq!(strip("playdate-vpc"), "playdate");
        assert_eq!(strip("playdate-app"), "playdate");
        assert_eq!(strip("fairfieldct-inbox"), "fairfieldct-inbox");
        assert_eq!(strip("vpc"), "vpc", "a bare layer word is a name");
        assert_eq!(strip("shop-app-db"), "shop-app", "only one token");
    }
}
