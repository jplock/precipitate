//! Name handling: slugs, environment tokens, prefixes, layers.

use precip_types::EnvName;
use std::collections::BTreeMap;

/// Lowercase, non-alphanumerics collapsed to single hyphens.
pub fn slug(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut last_dash = true;
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
            last_dash = false;
        } else if !last_dash {
            out.push('-');
            last_dash = true;
        }
    }
    while out.ends_with('-') {
        out.pop();
    }
    out
}

/// Split an environment token out of a slug, returning the remaining name
/// and the canonical environment. The end is checked first, then the
/// start, then any middle segment, so `app-dev-api` is `app-api` in `dev`.
pub fn split_environment(
    slug: &str,
    tokens: &BTreeMap<String, EnvName>,
) -> Option<(String, EnvName)> {
    let parts: Vec<&str> = slug.split('-').collect();
    if parts.len() < 2 {
        return None;
    }
    let order = std::iter::once(parts.len() - 1)
        .chain(std::iter::once(0))
        .chain(1..parts.len() - 1);
    for i in order {
        if let Some(env) = tokens.get(parts[i]) {
            let rest: Vec<&str> = parts
                .iter()
                .enumerate()
                .filter(|(j, _)| *j != i)
                .map(|(_, p)| *p)
                .collect();
            return Some((rest.join("-"), env.clone()));
        }
    }
    None
}

/// Drop a trailing segment that looks generated by CloudFormation or SAM:
/// 10 to 14 alphanumerics containing at least one digit, such as the
/// `7EMKNZP5FCB9` on `inbox-prod-rMailTable-7EMKNZP5FCB9`.
pub fn strip_generated_suffix(slug: &str) -> &str {
    let Some((head, tail)) = slug.rsplit_once('-') else { return slug };
    let looks_generated = (10..=14).contains(&tail.len())
        && tail.chars().all(|c| c.is_ascii_alphanumeric())
        && tail.chars().any(|c| c.is_ascii_digit());
    if looks_generated { head } else { slug }
}

/// An environment named by the account or its OU: the OU name contains a
/// token, or the account name starts or ends with one. Longest token wins.
pub fn environment_in_account(
    account_name: Option<&str>,
    ou_name: Option<&str>,
    tokens: &BTreeMap<String, EnvName>,
) -> Option<EnvName> {
    let account = account_name.map(slug);
    let ou = ou_name.map(slug);
    let mut best: Option<(&str, &EnvName)> = None;
    for (token, env) in tokens {
        let hit = ou.as_deref().is_some_and(|o| o.contains(token.as_str()))
            || account.as_deref().is_some_and(|a| {
                a.ends_with(&format!("-{token}"))
                    || a.starts_with(&format!("{token}-"))
            });
        if hit && best.is_none_or(|(t, _)| token.len() > t.len()) {
            best = Some((token, env));
        }
    }
    best.map(|(_, env)| env.clone())
}

/// The longest known name that `slug` equals or starts with (followed by
/// a hyphen).
pub fn longest_prefix<'a>(slug: &str, known: &'a [String]) -> Option<&'a str> {
    known
        .iter()
        .filter(|k| {
            !k.is_empty()
                && (slug == k.as_str() || slug.starts_with(&format!("{k}-")))
        })
        .max_by_key(|k| k.len())
        .map(String::as_str)
}

/// The shortest known name that `slug` equals or starts with (followed by
/// a hyphen), for finding the most general shared root among sibling
/// names. Equality counts so two resources with the same root join.
pub fn shortest_prefix<'a>(slug: &str, known: &'a [String]) -> Option<&'a str> {
    known
        .iter()
        .filter(|k| {
            !k.is_empty()
                && (slug == k.as_str() || slug.starts_with(&format!("{k}-")))
        })
        .min_by_key(|k| k.len())
        .map(String::as_str)
}

/// A known name that appears whole inside `slug` as a run of hyphen
/// separated segments, for example `vouch` in `cert-renewal-us-vouch-sh`.
/// Longest known name wins.
pub fn contains_segment<'a>(
    slug: &str,
    known: &'a [String],
) -> Option<&'a str> {
    let padded = format!("-{slug}-");
    known
        .iter()
        .filter(|k| !k.is_empty() && padded.contains(&format!("-{k}-")))
        .max_by_key(|k| k.len())
        .map(String::as_str)
}

/// The root `slug` shares with its siblings: the leading segments common
/// to the most siblings, longest on a tie. A one-segment root needs at
/// least three members in all; a longer root needs two. Roots that are
/// bare environment tokens are ignored.
pub fn shared_root(
    slug: &str,
    siblings: &[String],
    tokens: &BTreeMap<String, EnvName>,
) -> Option<String> {
    let segments: Vec<&str> = slug.split('-').collect();
    let mut best: Option<(usize, usize, String)> = None; // (count, len, root)
    for k in 1..segments.len() {
        let root = segments[..k].join("-");
        if tokens.contains_key(&root) {
            continue;
        }
        let count = siblings
            .iter()
            .filter(|s| *s == &root || s.starts_with(&format!("{root}-")))
            .count();
        let members = count + 1;
        let enough = if k == 1 { members >= 3 } else { members >= 2 };
        if !enough {
            continue;
        }
        let better = match &best {
            None => true,
            Some((c, l, _)) => count > *c || (count == *c && root.len() > *l),
        };
        if better {
            best = Some((count, root.len(), root));
        }
    }
    best.map(|(_, _, root)| root)
}

/// Remove one trailing layer token (`-vpc`, `-app`, `-db`) when a name
/// remains, so the layers of one workload share a name.
pub fn strip_layer(slug: &str, layers: &[String]) -> String {
    match slug.rsplit_once('-') {
        Some((head, tail))
            if !head.is_empty() && layers.iter().any(|l| l == tail) =>
        {
            head.to_string()
        }
        _ => slug.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tokens() -> BTreeMap<String, EnvName> {
        precip_types::GroupingConfig::default().environment_tokens
    }

    #[test]
    fn slug_normalises_names() {
        assert_eq!(slug("Search API (v2)"), "search-api-v2");
        assert_eq!(slug("--a--"), "a");
        assert_eq!(slug("billing_prod.v1"), "billing-prod-v1");
    }

    #[test]
    fn environment_splits_from_either_end_and_canonicalises() {
        let t = tokens();
        assert_eq!(
            split_environment("billing-prod", &t),
            Some(("billing".into(), "prod".into()))
        );
        assert_eq!(
            split_environment("production-billing", &t),
            Some(("billing".into(), "prod".into()))
        );
        assert_eq!(split_environment("billing", &t), None);
        assert_eq!(
            split_environment("prod", &t),
            None,
            "a bare token is a name, not an environment"
        );
    }

    #[test]
    fn environment_token_in_the_middle_is_found_last() {
        let t = tokens();
        assert_eq!(
            split_environment("app-dev-api", &t),
            Some(("app-api".into(), "dev".into()))
        );
        assert_eq!(
            split_environment("app-prod-discord-reminders", &t),
            Some(("app-discord-reminders".into(), "prod".into()))
        );
    }

    #[test]
    fn generated_suffixes_are_stripped() {
        assert_eq!(
            strip_generated_suffix("inbox-prod-rmailtable-7emknzp5fcb9"),
            "inbox-prod-rmailtable"
        );
        assert_eq!(
            strip_generated_suffix("inbox-prod-rmailtable"),
            "inbox-prod-rmailtable"
        );
        assert_eq!(strip_generated_suffix("ami-cleanup"), "ami-cleanup");
        assert_eq!(
            strip_generated_suffix("x-abcdefghijkl"),
            "x-abcdefghijkl",
            "no digit, not generated"
        );
    }

    #[test]
    fn account_and_ou_names_carry_an_environment() {
        let t = tokens();
        assert_eq!(
            environment_in_account(Some("payments-prod"), None, &t),
            Some("prod".into())
        );
        assert_eq!(
            environment_in_account(Some("payments"), Some("NonProd"), &t),
            Some("nonprod".into())
        );
        assert_eq!(
            environment_in_account(
                Some("payments"),
                Some("Infrastructure"),
                &t
            ),
            None
        );
        assert_eq!(
            environment_in_account(Some("production-tools"), None, &t),
            Some("prod".into())
        );
    }

    #[test]
    fn longest_prefix_prefers_the_most_specific_name() {
        let known =
            ["vouch".to_string(), "vouch-us".to_string(), "inbox".to_string()];
        assert_eq!(
            longest_prefix("vouch-us-prod-instance-refresh", &known),
            Some("vouch-us")
        );
        assert_eq!(longest_prefix("vouch", &known), Some("vouch"));
        assert_eq!(
            longest_prefix("voucher-x", &known),
            None,
            "prefix must end at a hyphen"
        );
    }

    #[test]
    fn shortest_prefix_finds_the_shared_root() {
        let known =
            ["fairfieldct-ai".to_string(), "fairfieldct-ai-api".to_string()];
        assert_eq!(
            shortest_prefix("fairfieldct-ai-api-v2", &known),
            Some("fairfieldct-ai")
        );
        assert_eq!(
            shortest_prefix("fairfieldct-ai", &known),
            Some("fairfieldct-ai"),
            "an identical sibling root counts"
        );
    }

    #[test]
    fn contains_segment_matches_whole_segments_only() {
        let known = ["vouch".to_string(), "us".to_string()];
        assert_eq!(
            contains_segment("cert-renewal-us-vouch-sh", &known),
            Some("vouch")
        );
        assert_eq!(contains_segment("voucher-renewal", &known), None);
    }

    #[test]
    fn shared_root_picks_the_root_most_siblings_share() {
        let t = tokens();
        let sibs: Vec<String> = [
            "serverless-create-root-ca",
            "serverless-issuing-ca-crl",
            "serverless-root-ca-crl",
            "serverless-tls-cert",
            "serverless-expiry",
        ]
        .map(str::to_string)
        .to_vec();
        assert_eq!(
            shared_root("serverless-create-issuing-ca", &sibs, &t),
            Some("serverless".into())
        );
        let two: Vec<String> = vec!["aws-quicksetup-ssm".to_string()];
        assert_eq!(
            shared_root("aws-messaging-webhook", &two, &t),
            None,
            "one segment needs three members"
        );
        let pair: Vec<String> = vec!["inbox-mail-sender".to_string()];
        assert_eq!(
            shared_root("inbox-mail-webhook", &pair, &t),
            Some("inbox-mail".into())
        );
    }

    #[test]
    fn layer_tokens_fold_into_the_workload_name() {
        let layers = precip_types::GroupingConfig::default().layer_tokens;
        assert_eq!(strip_layer("playdate-vpc", &layers), "playdate");
        assert_eq!(strip_layer("playdate-app", &layers), "playdate");
        assert_eq!(
            strip_layer("fairfieldct-inbox", &layers),
            "fairfieldct-inbox"
        );
        assert_eq!(
            strip_layer("vpc", &layers),
            "vpc",
            "a bare layer word is a name"
        );
        assert_eq!(
            strip_layer("shop-app-db", &layers),
            "shop-app",
            "only one token"
        );
    }
}
